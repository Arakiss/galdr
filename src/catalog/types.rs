pub const STATUS_DRAFT: &str = "draft";
pub const STATUS_FINAL: &str = "final";
pub const STATUS_PARAM_DRAFT: &str = "param-draft";
pub const STATUS_UNKNOWN: &str = "unknown";

/// One row of the recordings list.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RecordingRow {
    pub rec_id: String,
    pub name: String,
    pub started_at: String,
    pub ended_at: Option<String>,
    pub steps: i64,
    pub cwd: Option<String>,
    /// Whether a skill has been distilled from this recording.
    pub distilled: bool,
}

/// One step within a recording (the index view, no raw blobs).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StepRow {
    pub seq: i64,
    pub tool_name: String,
    #[serde(default = "default_event_kind")]
    pub event_kind: String,
    pub ts: String,
    pub summary: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub judgments: Vec<StepJudgmentRow>,
}

/// A recording together with its steps.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RecordingDetail {
    pub recording: RecordingRow,
    pub steps: Vec<StepRow>,
}

/// One external judgment attached to a recorded step.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StepJudgmentRow {
    pub event_id: String,
    pub rec_id: String,
    pub seq: i64,
    pub verdict: String,
    pub rationale: String,
    pub suggested_action: Option<String>,
    pub judge: Option<String>,
    pub task_key: String,
    pub created_at: String,
}

/// One installed skill and its provenance.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SkillRow {
    pub skill_name: String,
    pub rec_id: Option<String>,
    pub skill_path: String,
    pub installed_at: Option<String>,
    pub status: String,
    pub readiness_score: i64,
    pub readiness_delta: i64,
    pub readiness_notes: String,
    /// `true` if the skill's recording is missing (or it has no provenance).
    pub orphan: bool,
    /// `"galdr"` if galdr distilled this skill, `"external"` if it was authored by
    /// hand or another harness and merely lives under the shared skills directory.
    #[serde(default = "default_skill_origin")]
    pub origin: String,
}

/// Skill installed by galdr's distillation.
pub const ORIGIN_GALDR: &str = "galdr";
/// Skill that lives under the skills directory but galdr did not create.
pub const ORIGIN_EXTERNAL: &str = "external";

fn default_skill_origin() -> String {
    ORIGIN_EXTERNAL.to_string()
}

fn default_event_kind() -> String {
    "tool_call".to_string()
}

/// Classifies a skill by reading its `SKILL.md`. A galdr-distilled skill carries a
/// provenance marker — a `rec_id` line, a draft banner, or a `galdr` command — that
/// a hand-authored or other-harness skill under the same directory does not.
pub fn skill_origin(skill_path: &str) -> &'static str {
    match std::fs::read_to_string(skill_path) {
        Ok(md) if md_is_galdr(&md) => ORIGIN_GALDR,
        _ => ORIGIN_EXTERNAL,
    }
}

fn md_is_galdr(md: &str) -> bool {
    md.contains("rec_id:")
        || md.contains("[galdr DRAFT]")
        || md.contains("galdr distill")
        || md.contains("galdr parametrize")
        || md.contains("Draft generated by `galdr")
}

